"""Generate the public source catalog from the manifest and verified local corpus.

Run normally to write web/src/reportCatalog.ts. Run with --check in CI to fail
when a PDF, its metadata, the Chroma collection, or generated catalog drifts.
"""

import argparse
import hashlib
import json
import re
from collections import Counter
from pathlib import Path
from urllib.parse import urlparse

import chromadb
from pypdf import PdfReader


ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "data" / "report_manifest.json"
PDF_DIR = ROOT / "data" / "reports_pdfs"
CATALOG = ROOT / "web" / "src" / "reportCatalog.ts"


def generate() -> str:
    reports = json.loads(MANIFEST.read_text(encoding="utf-8"))
    assert len(reports) == len({item["file"] for item in reports}), "duplicate manifest file"
    assert {item["file"] for item in reports} == {pdf.name for pdf in PDF_DIR.glob("*.pdf")}, "manifest/PDF set mismatch"
    client = chromadb.PersistentClient(path=str(ROOT / "chroma_store"))
    collection = client.get_collection("economic_reports")
    rows = collection.get(include=["metadatas"])
    counts = Counter(chunk_id.split("_chunk_")[0] for chunk_id in rows["ids"])
    assert sum(counts.values()) == collection.count(), "unexpected chunk ID format"
    assert set(counts) == {Path(item["file"]).stem for item in reports}, "manifest/Chroma source mismatch"

    for chunk_id, metadata in zip(rows["ids"], rows["metadatas"]):
        if "_2026_chunk_" in chunk_id:
            assert metadata and metadata.get("page", 0) > 0, f"missing PDF page: {chunk_id}"
            assert metadata.get("source_file") == f"{chunk_id.split('_chunk_')[0]}.pdf", chunk_id

    output = [
        "// Generated by scripts/generate_report_catalog.py from data/report_manifest.json",
        "// and chroma_store. Edit the manifest and regenerate; CI checks for drift.",
        "export type ReportSource = {",
        "  id: string; title: string; publisher: string; issue: string; pages: number; chunks: number;",
        "  url: string; sha256: string; publicPassage: boolean;",
        "};",
        "export const REPORT_SOURCES: ReportSource[] = [",
    ]
    indexed = list(enumerate(reports))
    indexed.sort(key=lambda pair: (-int(re.search(r"20\d{2}", pair[1]["issue"]).group()), pair[0]))
    for _, report in indexed:
        pdf = PDF_DIR / report["file"]
        digest = hashlib.sha256(pdf.read_bytes()).hexdigest()
        assert digest == report["sha256"], f"PDF checksum drift: {pdf.name}"
        assert len(PdfReader(str(pdf)).pages) == report["pages"], f"PDF page count drift: {pdf.name}"
        assert urlparse(report["url"]).scheme == "https", f"non-HTTPS source: {pdf.name}"
        report_id = pdf.stem
        assert counts[report_id] > 0, f"no chunks: {report_id}"
        fields = {
            "id": report_id, "title": report["title"], "publisher": report["publisher"],
            "issue": report["issue"], "pages": report["pages"], "chunks": counts[report_id],
            "url": report["url"], "sha256": report["sha256"],
            "publicPassage": bool(report.get("public_passage", False)),
        }
        literal = ", ".join(f"{key}: {json.dumps(value, ensure_ascii=False)}" for key, value in fields.items())
        output.append(f"  {{ {literal} }},")
    output.extend(["];", ""])
    return "\n".join(output)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if CATALOG.read_text(encoding="utf-8").replace("\r\n", "\n") != generated:
            raise SystemExit("Report catalog is stale; run python scripts/generate_report_catalog.py")
        print("Report catalog, PDFs, manifest and Chroma source counts match.")
    else:
        CATALOG.write_text(generated, encoding="utf-8")
        print(f"Wrote {CATALOG}")
